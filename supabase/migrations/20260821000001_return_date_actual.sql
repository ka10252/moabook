-- 반납일 = 실제로 돌려받은 날
--
-- 지금까지 `return_date` 는 **대여를 수락할 때 약속한 예정일**만 담았다. 그래서
--   · 예정일을 안 정하고 빌려준 거래 → 반납이 끝났는데도 "반납일: 미정"
--   · 예정일보다 늦게 돌려받은 거래 → 실제 날짜를 알 수 없음
-- 이 되었다. 앞으로 이 칸은 **진행 중이면 예정일, 끝났으면 실제 반납일**을 담는다.
-- 완료 처리는 앱이 한다 (src/utils/transactionHelpers.ts, src/hooks/useTransactions.ts).
COMMENT ON COLUMN public.transactions.return_date IS
  '진행 중이면 반납 예정일, 완료되면 실제 반납일';

-- ⚠️ 지난 거래 채우기는 **여기서 하지 않는다.**
--    `UPDATE … FROM LATERAL (…)` 로 채팅의 '[반납 완료]' 시각을 끌어오려 했는데
--    한 행도 바뀌지 않았다. 조용히 0행인 SQL은 돌렸는지조차 확인할 수 없었다.
--    게다가 같은 책을 여러 번 빌린 경우(완료 거래 3건 + 메시지 4건) 짝을 맞추려면
--    "한 번 쓴 메시지는 다시 쓰지 않는다" 같은 상태가 필요해 SQL로 쓰기에 나쁘다.
--    → `npm run returndate:backfill` 로 옮겼다. 무엇을 어디에 넣는지 한 줄씩 찍는다.
--      (실행 완료: 2026-08-19, 10건)
