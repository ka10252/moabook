-- 책 상태에 '사용감 많음' 단계를 추가한다.
--
-- 기존 S/A/B는 알파벳만 보여줘서 뜻이 안 읽혔다(유저 피드백: "딱히 의미 부여하는 바가 없음").
-- 화면에서는 알파벳을 지우고 한국어 문구만 쓰지만, DB 값은 그대로 두고 C만 더한다.
-- 값을 갈아엎으면 이미 올라간 책 데이터를 전부 옮겨야 하고 되돌릴 수도 없다.
--   S = 새 책 · A = 양호 · B = 보통 · C = 사용감 많음
--
-- ⚠️ 이 파일은 ALTER TYPE ADD VALUE 하나만 담는다. 같은 트랜잭션 안에서는
--    방금 추가한 enum 값을 쓸 수 없어서, 이 값을 사용하는 문장과 섞으면 실패한다.
ALTER TYPE public.book_condition ADD VALUE IF NOT EXISTS 'C';
